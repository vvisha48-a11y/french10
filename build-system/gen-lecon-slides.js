// Generate t13-lecons.html — the 217 vocabulary slides — from the authored
// content of the separate "10th lessons" project.
//
// The 74 content files are inert HTML: no <script>, no Reveal/Deck references,
// and (bar two already-l4-prefixed SVG defs) no id attributes. Everything they
// need is wired from outside by class name, which is what makes this merge safe.
//
// Slide ids are l2-…l10- prefixed and the deck's are let-/use-/neg-/msg-/… , so
// nothing collides. Verified: zero overlap on data-slide-id and on data-topic.
//
// Run by build.sh alongside gen-letter-slides.js / gen-message-slides.js.
const fs = require('fs');
const path = require('path');

const SRC     = 'C:/10th lessons/build';
const CONTENT = path.join(SRC, 'content');
const OUT     = path.join(__dirname, 't13-lecons.html');

if (!fs.existsSync(CONTENT)) {
  console.error('lecon content not found: ' + CONTENT);
  process.exit(1);
}

/* ---------- the slide order ----------
   Taken from the CONTENT array in that project's build.mjs rather than copied,
   so the two never drift. Parsed, not imported: build.mjs is ESM and reads a
   13 MB source file at import time. */
const buildMjs = fs.readFileSync(path.join(SRC, 'build.mjs'), 'utf8');
const arrStart = buildMjs.indexOf('const CONTENT = [');
const arrEnd   = buildMjs.indexOf('].map(', arrStart);
if (arrStart === -1 || arrEnd === -1) {
  console.error('could not locate the CONTENT array in build.mjs');
  process.exit(1);
}
const ORDER = [...buildMjs.slice(arrStart, arrEnd).matchAll(/'([^']+\.html)'/g)].map(m => m[1]);
if (ORDER.length < 70) {
  console.error('CONTENT array parsed as only ' + ORDER.length + ' files — refusing to build a partial deck');
  process.exit(1);
}

/* ---------- image placeholders ----------
   expand() is a port of build.mjs:41-76. The emitted markup must stay
   byte-compatible with what that build produces, because extra.js keys off
   data-fb and the CSS keys off .photo-block / .topic-visual / .usage-caption. */
const IMG = JSON.parse(fs.readFileSync(path.join(SRC, 'images.json'), 'utf8'));
const esc = s => String(s == null ? '' : s)
  .replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const missing = [];
function expand(html) {
  const pick = k => { const r = IMG[k]; if (!r) missing.push(k); return r; };

  html = html.replace(/\{\{(img|tvimg):([a-z0-9-]+)\}\}/g, (_, kind, k) => {
    const r = pick(k); if (!r) return '';
    const cls = kind === 'tvimg' ? 'topic-visual' : 'usage-photo';
    return '<img class="' + cls + '" src="' + esc(r.url) + '" alt="' + esc(r.alt) + '" ' +
           'loading="lazy" decoding="async" referrerpolicy="no-referrer" data-fb="' + esc(r.cap) + '">';
  });

  html = html.replace(/\{\{photo:([a-z0-9-]+)\}\}/g, (_, k) => {
    const r = pick(k); if (!r) return '';
    return '<div class="photo-block">' +
           '<img src="' + esc(r.url) + '" alt="' + esc(r.alt) + '" loading="lazy" decoding="async" ' +
           'referrerpolicy="no-referrer" data-fb="' + esc(r.cap) + '">' +
           '<p class="usage-caption">' + esc(r.cap) + ' — ' + esc(r.credit) + '</p></div>';
  });

  /* data-fb is deliberately EMPTY and alt is generic: in the photo-to-word game
     the caption IS the answer, so naming the photo would hand the class every pair. */
  html = html.replace(/\{\{pmimg:([a-z0-9-]+)\}\}/g, (_, k) => {
    const r = pick(k); if (!r) return '';
    return '<img src="' + esc(r.url) + '" alt="Photo à associer à un mot" loading="lazy" ' +
           'decoding="async" referrerpolicy="no-referrer" data-fb="">';
  });

  html = html.replace(/\{\{cap:([a-z0-9-]+)\}\}/g, (_, k) => {
    const r = pick(k); if (!r) return '';
    return esc(r.cap) + ' — ' + esc(r.credit);
  });

  html = html.replace(/\{\{credit:([a-z0-9-]+)\}\}/g, (_, k) => {
    const r = pick(k); if (!r) return '';
    return esc(r.credit);
  });

  return html;
}

/* ---------- assemble ---------- */
let out = '\n<!-- ===== LES LEÇONS — vocabulaire (generated by gen-lecon-slides.js) ===== -->\n';
let stacks = 0, slides = 0;

ORDER.forEach(f => {
  const p = path.join(CONTENT, f);
  if (!fs.existsSync(p)) { console.error('missing content file: ' + f); process.exit(1); }
  let h = expand(fs.readFileSync(p, 'utf8'));

  /* Tag every vertical slide so the lesson CSS can be scoped to it. The class
     goes AFTER data-step on purpose: verify.js:128 matches
     <section data-slide-id="…" data-step="…"  and putting anything between
     them would hide these slides from the deck's own structural checks. */
  h = h.replace(/<section data-slide-id="([^"]*)" data-step="([^"]*)">/g,
    (m, id, step) => '<section data-slide-id="' + id + '" data-step="' + step + '" class="lecon-slide">');

  stacks += (h.match(/<section data-topic=/g) || []).length;
  slides += (h.match(/<section data-slide-id=/g) || []).length;
  out += h.trimEnd() + '\n\n';
});

if (missing.length) {
  console.error('unknown image key(s): ' + [...new Set(missing)].join(', '));
  process.exit(1);
}

/* Nothing may reach the shipped deck still holding a placeholder. */
const leftover = out.match(/\{\{[a-z]+:[a-z0-9-]+\}\}/g);
if (leftover) {
  console.error('unexpanded placeholder(s): ' + [...new Set(leftover)].join(', '));
  process.exit(1);
}

const tagged = (out.match(/class="lecon-slide"/g) || []).length;
if (tagged !== slides) {
  console.error('only ' + tagged + ' of ' + slides + ' slides got .lecon-slide — the CSS scope would leak');
  process.exit(1);
}

fs.writeFileSync(OUT, out);
console.log('  lecon slides     : ' + slides + ' in ' + stacks + ' stacks -> t13-lecons.html');
console.log('  files            : ' + ORDER.length);
console.log('  photos referenced: ' + (out.match(/upload\.wikimedia\.org/g) || []).length +
            ' (inlined later by inline-lecon-photos.js)');
