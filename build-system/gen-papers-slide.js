// Generate t14-papers.html -- the Question Papers slide -- from papers-ui.js.
//
//   node gen-papers-slide.js        (build.sh runs it after gen-papers.js)
//
// Every byte of the module comes from papers-ui.js: the same CSS, the same page
// markup (PAGE), the same data script (DATA) and the same engine (JS) that the
// Phase 1 lab is built from. This file only adds the slide around them, so the
// lab and the deck cannot drift -- check-papers.js compares the bytes in both.
//
// Three rules the deck imposes, all asserted below before anything is written:
//   * exactly one stack with one slide. build.sh appends it LAST, because deep
//     links (#/h/v) and saved progress are keyed by stack index;
//   * no nested <section>. b-style.html gives every section inside .slides
//     height:100%, and Reveal's overview mode clips them;
//   * nothing in the data can close the <script> it is embedded in.
//
// The module does not start itself. The engine calls PapersModule.activate(card)
// from updateHud() when this slide is current -- see syncPapers() in e-engine.html.

const fs = require('fs');
const path = require('path');
const UI = require('./papers-ui.js');

const OUT = path.join(__dirname, 't14-papers.html');
const dataFile = path.join(__dirname, 'paperdata.js');
if (!fs.existsSync(dataFile)){ console.error('paperdata.js missing -- run gen-papers.js first'); process.exit(1); }
delete require.cache[require.resolve(dataFile)];
const { PAPERS, TAXONOMY, TENSES } = require(dataFile);

const markup = [
  '<!-- ===== QUESTION PAPERS (generated by gen-papers-slide.js from papers-ui.js -- do not edit) ===== -->',
  '<style>',
  UI.CSS,
  '</style>',
  '<section data-topic="papers" data-topic-name="Question Papers" data-sub="Les épreuves">',
  '  <section data-slide-id="papers-1" data-step="Les épreuves" class="pl-slide">',
  '    <div class="slide-card pl-card">',
  '      <div class="flag-stripe"></div>',
  UI.PAGE(PAPERS),
  '    </div>',
  '  </section>',
  '</section>'
].join('\n');

const out = markup + '\n' + [
  '<script>',
  UI.DATA(PAPERS, TAXONOMY, TENSES),
  '</script>',
  '<script>',
  UI.JS,
  '</script>',
  ''
].join('\n');

/* ---- self-check ---- */
const problems = [];
const sections = (markup.match(/<section\b/g) || []).length;
if (sections !== 2) problems.push('expected 2 <section> tags (the stack and its slide), found ' + sections);
if (markup.indexOf('<section class="pl-paper"') !== -1) problems.push('.pl-paper is still a <section>');
const ids = {};
[...markup.matchAll(/\sid="([^"]+)"/g)].forEach(m => { ids[m[1]] = (ids[m[1]] || 0) + 1; });
const dup = Object.keys(ids).filter(k => ids[k] > 1);
if (dup.length) problems.push(dup.length + ' duplicated id(s): ' + dup.slice(0, 6).join(', '));
const closers = (out.match(/<\/script/gi) || []).length;
if (closers !== 2) problems.push('expected 2 </script> closers, found ' + closers + ' -- something in the data or engine closes a script early');
if (UI.JS.indexOf('window.PapersModule') === -1) problems.push('the engine no longer defines window.PapersModule');

if (problems.length){
  console.error('gen-papers-slide.js: refusing to write t14-papers.html');
  problems.forEach(p => console.error('   x ' + p));
  process.exit(1);
}

fs.writeFileSync(OUT, out);
const qs = PAPERS.reduce((n, p) => n + p.sections.reduce((m, s) => m + s.questions.filter(q => !q.isContainer).length, 0), 0);
console.log('  papers slide     : ' + PAPERS.length + ' papers, ' + qs + ' questions, ' +
  Object.keys(ids).length + ' ids -> t14-papers.html (' + (out.length / 1024).toFixed(0) + ' KB)');
